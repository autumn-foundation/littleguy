//! The cargo features of the workspace: the build matrix and the feature
//! table of `docs/features.md`.
//!
//! The table comes from the manifests. `cargo metadata` gives the features
//! of each crate and its optional dependencies. The comment above each
//! feature in `Cargo.toml` gives its description. So the table cannot
//! drift from the code: `cargo xtask feature-docs` fails when the file
//! differs from a new render, and `--write` renders it again.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

use smop::prelude::*;
use smop::serde_json::Value;

/// The file that holds the feature table.
pub const DOC: &str = "docs/features.md";

/// The line before the generated table.
const BEGIN: &str = "<!-- features:begin (generated by `cargo xtask feature-docs --write`) -->";

/// The line after the generated table.
const END: &str = "<!-- features:end -->";

/// One crate of the workspace that has features.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Crate {
    /// The package name.
    pub name: String,
    /// The path of its manifest.
    pub manifest: String,
    /// Each feature and what it turns on, as `cargo metadata` gives them.
    pub features: BTreeMap<String, Vec<String>>,
    /// The optional dependencies of the crate.
    pub optional: BTreeSet<String>,
}

/// Reads the crates of the workspace that have features, in the order of
/// `cargo metadata`.
///
/// # Errors
///
/// Returns an error when `cargo metadata` fails or its answer does not
/// parse.
pub fn workspace(root: &Path) -> Result<Vec<Crate>> {
    let text = sh::cargo()
        .args(["metadata", "--format-version", "1", "--no-deps", "--locked"])
        .dir(root)
        .output()?;
    parse_metadata(&text)
}

/// The crates with features in the metadata `text`.
///
/// # Errors
///
/// Returns an error when `text` is not the JSON of `cargo metadata`.
pub fn parse_metadata(text: &str) -> Result<Vec<Crate>> {
    let metadata: Value = smop::serde_json::from_str(text).context("cargo metadata")?;
    let packages = metadata["packages"]
        .as_array()
        .context("cargo metadata has no packages")?;
    let mut crates = Vec::new();
    for package in packages {
        let features: BTreeMap<String, Vec<String>> = package["features"]
            .as_object()
            .map(|map| {
                map.iter()
                    .map(|(name, items)| {
                        let items = items
                            .as_array()
                            .map(|items| {
                                items
                                    .iter()
                                    .filter_map(Value::as_str)
                                    .map(str::to_owned)
                                    .collect()
                            })
                            .unwrap_or_default();
                        (name.clone(), items)
                    })
                    .collect()
            })
            .unwrap_or_default();
        if features.is_empty() {
            continue;
        }
        let optional = package["dependencies"]
            .as_array()
            .map(|deps| {
                deps.iter()
                    .filter(|dep| dep["optional"].as_bool() == Some(true))
                    .filter_map(|dep| dep["name"].as_str().map(str::to_owned))
                    .collect()
            })
            .unwrap_or_default();
        crates.push(Crate {
            name: package["name"].as_str().unwrap_or_default().to_owned(),
            manifest: package["manifest_path"]
                .as_str()
                .unwrap_or_default()
                .to_owned(),
            features,
            optional,
        });
    }
    Ok(crates)
}

/// What one feature brings into a build.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct Adds {
    /// The optional crates that the feature adds, across the workspace.
    pub crates: BTreeSet<String>,
    /// The features of outside crates that it turns on, as `crate/feature`.
    pub outside: BTreeSet<String>,
}

/// What `feature` of `name` brings in. It follows each feature of a
/// workspace crate that `feature` turns on.
#[must_use]
pub fn adds(crates: &[Crate], name: &str, feature: &str) -> Adds {
    let mut adds = Adds::default();
    let mut seen = BTreeSet::new();
    walk(crates, name, feature, &mut adds, &mut seen);
    adds
}

fn walk(
    crates: &[Crate],
    name: &str,
    feature: &str,
    adds: &mut Adds,
    seen: &mut BTreeSet<(String, String)>,
) {
    if !seen.insert((name.to_owned(), feature.to_owned())) {
        return;
    }
    let Some(krate) = crates.iter().find(|krate| krate.name == name) else {
        return;
    };
    for item in krate.features.get(feature).into_iter().flatten() {
        if let Some(dep) = item.strip_prefix("dep:") {
            adds.crates.insert(dep.to_owned());
        } else if let Some((dep, inner)) = item.split_once('/') {
            let dep = dep.trim_end_matches('?');
            if krate.optional.contains(dep) {
                adds.crates.insert(dep.to_owned());
            }
            if crates.iter().any(|krate| krate.name == dep) {
                walk(crates, dep, inner, adds, seen);
            } else {
                adds.outside.insert(format!("{dep}/{inner}"));
            }
        } else {
            walk(crates, name, item, adds, seen);
        }
    }
}

/// The comment above each feature of the manifest `text`, by feature.
#[must_use]
pub fn comments(text: &str) -> BTreeMap<String, String> {
    let mut found = BTreeMap::new();
    let mut in_features = false;
    let mut comment: Vec<&str> = Vec::new();
    for line in text.lines() {
        let line = line.trim();
        if line.starts_with('[') && !line.starts_with("[\"") {
            in_features = line == "[features]";
            comment.clear();
            continue;
        }
        if !in_features {
            continue;
        }
        if let Some(rest) = line.strip_prefix('#') {
            comment.push(rest.trim());
            continue;
        }
        let name = line
            .split_once('=')
            .map(|(name, _)| name.trim())
            .filter(|name| !name.is_empty() && !name.starts_with('"'));
        if let Some(name) = name.filter(|_| !comment.is_empty()) {
            found.insert(name.to_owned(), comment.join(" "));
        }
        comment.clear();
    }
    found
}

/// Renders the feature table of `crates`. `manifest` reads the text of a
/// manifest. A feature without a comment is an error, so each feature
/// says what it is for.
///
/// # Errors
///
/// Returns an error when a manifest does not read or a feature has no
/// comment.
pub fn render(crates: &[Crate], manifest: impl Fn(&str) -> Result<String>) -> Result<String> {
    let mut out = String::new();
    let mut missing = Vec::new();
    for krate in crates {
        let notes = comments(&manifest(&krate.manifest)?);
        let defaults: BTreeSet<&str> = krate
            .features
            .get("default")
            .into_iter()
            .flatten()
            .map(String::as_str)
            .collect();
        let _ = write!(out, "\n### `{}`\n\n", krate.name);
        out.push_str("| Feature | Default | What it builds | Crates it adds |\n");
        out.push_str("|---|---|---|---|\n");
        for feature in krate.features.keys().filter(|name| *name != "default") {
            let Some(note) = notes.get(feature) else {
                missing.push(format!("{}/{feature}", krate.name));
                continue;
            };
            let adds = adds(crates, &krate.name, feature);
            let mut pulled: Vec<String> = adds.crates.iter().map(|c| format!("`{c}`")).collect();
            pulled.extend(adds.outside.iter().map(|f| format!("`{f}`")));
            let pulled = if pulled.is_empty() {
                String::from("none")
            } else {
                pulled.join(", ")
            };
            let default = if defaults.contains(feature.as_str()) {
                "yes"
            } else {
                "no"
            };
            let _ = writeln!(out, "| `{feature}` | {default} | {note} | {pulled} |");
        }
    }
    if !missing.is_empty() {
        bail!(
            "each feature needs a comment above it in Cargo.toml: {}",
            missing.join(", ")
        );
    }
    Ok(out)
}

/// Puts `table` between the markers of `doc`.
///
/// # Errors
///
/// Returns an error when `doc` lacks a marker.
pub fn splice(doc: &str, table: &str) -> Result<String> {
    let start = doc
        .find(BEGIN)
        .with_context(|| format!("{DOC} has no line `{BEGIN}`"))?;
    let end = doc
        .find(END)
        .with_context(|| format!("{DOC} has no line `{END}`"))?;
    ensure!(start < end, "{DOC} has its markers in the wrong order");
    Ok(format!(
        "{}{BEGIN}\n{table}\n{}",
        &doc[..start],
        &doc[end..]
    ))
}

/// Checks `docs/features.md`, or writes it with `write`.
///
/// # Errors
///
/// Returns an error when the file differs from a new render and `write`
/// is off, or when a step fails.
pub fn docs(root: &Path, write: bool) -> Result<()> {
    let crates = workspace(root)?;
    let table = render(&crates, |manifest| {
        std::fs::read_to_string(manifest).with_context(|| format!("reading {manifest}"))
    })?;
    let path = root.join(DOC);
    let doc = std::fs::read_to_string(&path).with_context(|| format!("reading {DOC}"))?;
    let fresh = splice(&doc, &table)?;
    if fresh == doc {
        return Ok(());
    }
    if write {
        std::fs::write(&path, fresh).with_context(|| format!("writing {DOC}"))?;
        return Ok(());
    }
    bail!("{DOC} is out of date. Run `cargo xtask feature-docs --write`")
}

/// The settings of a lean build: no debug info, no incremental state.
const LEAN: [(&str, &str); 2] = [("CARGO_PROFILE_DEV_DEBUG", "0"), ("CARGO_INCREMENTAL", "0")];

/// The feature sets to check for one crate: none, each feature alone, and
/// all of them.
#[must_use]
pub fn matrix(krate: &Crate) -> Vec<Vec<String>> {
    let none = vec![String::from("--no-default-features")];
    let alone = krate
        .features
        .keys()
        .filter(|name| *name != "default")
        .map(|name| {
            vec![
                String::from("--no-default-features"),
                String::from("--features"),
                name.clone(),
            ]
        });
    let all = vec![String::from("--all-features")];
    std::iter::once(none)
        .chain(alone)
        .chain(std::iter::once(all))
        .collect()
}

/// Runs clippy on every target of each crate with features, for each set
/// of [`matrix`], with warnings denied. Then runs the tests of each crate
/// with no features.
///
/// Each feature set builds its own copy of the dependencies, so the matrix
/// fills a disk fast. It builds without debug info and without incremental
/// state, which cuts the size of each copy several times.
///
/// # Errors
///
/// Returns an error at the first set that fails.
pub fn check(root: &Path) -> Result<()> {
    let crates = workspace(root)?;
    for krate in &crates {
        for set in matrix(krate) {
            sh::cargo()
                .args(["clippy", "--locked", "--all-targets", "-p", &krate.name])
                .args(&set)
                .args(["--", "-D", "warnings"])
                .env(LEAN[0].0, LEAN[0].1)
                .env(LEAN[1].0, LEAN[1].1)
                .dir(root)
                .echo()
                .run()?;
        }
        sh::cargo()
            .args([
                "test",
                "--locked",
                "-p",
                &krate.name,
                "--no-default-features",
            ])
            .env(LEAN[0].0, LEAN[0].1)
            .env(LEAN[1].0, LEAN[1].1)
            .dir(root)
            .echo()
            .run()?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn krate(name: &str, features: &[(&str, &[&str])], optional: &[&str]) -> Crate {
        Crate {
            name: name.to_owned(),
            manifest: format!("{name}/Cargo.toml"),
            features: features
                .iter()
                .map(|(name, items)| {
                    (
                        (*name).to_owned(),
                        items.iter().map(|item| (*item).to_owned()).collect(),
                    )
                })
                .collect(),
            optional: optional.iter().map(|dep| (*dep).to_owned()).collect(),
        }
    }

    fn sample() -> Vec<Crate> {
        vec![
            krate(
                "inner",
                &[("default", &["web"]), ("web", &["dep:reqwest", "dep:url"])],
                &["reqwest", "url"],
            ),
            krate(
                "outer",
                &[
                    ("default", &["web"]),
                    ("web", &["inner/web"]),
                    ("box", &["harvest/sandbox", "dep:camel"]),
                    ("full", &["web", "box"]),
                ],
                &["camel"],
            ),
        ]
    }

    #[test]
    fn a_feature_adds_the_crates_of_the_features_it_follows() {
        let crates = sample();
        let web = adds(&crates, "outer", "web");
        assert_eq!(
            web.crates,
            BTreeSet::from([String::from("reqwest"), String::from("url")])
        );
        let full = adds(&crates, "outer", "full");
        assert!(full.crates.contains("camel"));
        assert!(full.crates.contains("reqwest"));
        assert_eq!(
            full.outside,
            BTreeSet::from([String::from("harvest/sandbox")])
        );
        assert_eq!(adds(&crates, "outer", "gone"), Adds::default());
    }

    #[test]
    fn each_comment_belongs_to_the_feature_below_it() {
        let text = "[package]\n# not this\nname = \"x\"\n\n[features]\ndefault = [\"web\"]\n\
                    # The web.\n# Two lines.\nweb = [\n    \"dep:url\",\n]\n\n[lints]\n";
        let found = comments(text);
        assert_eq!(
            found.get("web").map(String::as_str),
            Some("The web. Two lines.")
        );
        assert!(!found.contains_key("default"));
        assert!(!found.contains_key("name"));
    }

    #[test]
    fn the_table_needs_a_comment_for_each_feature() {
        let crates = sample();
        let manifest = |path: &str| -> Result<String> {
            Ok(match path {
                "inner/Cargo.toml" => String::from("[features]\n# Fetch.\nweb = []\n"),
                _ => String::from("[features]\n# Web.\nweb = []\n# Box.\nbox = []\n"),
            })
        };
        let error = render(&crates, manifest).unwrap_err().to_string();
        assert!(error.contains("outer/full"), "{error}");
        let manifest = |path: &str| -> Result<String> {
            Ok(match path {
                "inner/Cargo.toml" => String::from("[features]\n# Fetch.\nweb = []\n"),
                _ => String::from(
                    "[features]\n# Web.\nweb = []\n# Box.\nbox = []\n# All.\nfull = []\n",
                ),
            })
        };
        let table = render(&crates, manifest).unwrap();
        assert!(
            table.contains("| `web` | yes | Fetch. | `reqwest`, `url` |"),
            "{table}"
        );
        assert!(
            table.contains("| `box` | no | Box. | `camel`, `harvest/sandbox` |"),
            "{table}"
        );
    }

    #[test]
    fn the_table_goes_between_the_markers() {
        let doc = format!("# Title\n\n{BEGIN}\nold\n{END}\n\nAfter.\n");
        let spliced = splice(&doc, "new").unwrap();
        assert_eq!(
            spliced,
            format!("# Title\n\n{BEGIN}\nnew\n{END}\n\nAfter.\n")
        );
        assert!(splice("no markers", "new").is_err());
    }

    #[test]
    fn the_matrix_has_none_each_and_all() {
        let crates = sample();
        let sets = matrix(&crates[1]);
        assert_eq!(sets.len(), 5);
        assert_eq!(sets[0], ["--no-default-features"]);
        assert_eq!(sets[1], ["--no-default-features", "--features", "box"]);
        assert_eq!(sets[4], ["--all-features"]);
    }

    #[test]
    fn the_metadata_gives_the_crates_with_features() {
        let text = r#"{"packages": [
            {"name": "plain", "manifest_path": "/p/Cargo.toml", "features": {}, "dependencies": []},
            {"name": "inner", "manifest_path": "/i/Cargo.toml",
             "features": {"web": ["dep:url"]},
             "dependencies": [{"name": "url", "optional": true}, {"name": "serde", "optional": false}]}
        ]}"#;
        let crates = parse_metadata(text).unwrap();
        assert_eq!(crates.len(), 1);
        assert_eq!(crates[0].name, "inner");
        assert_eq!(crates[0].optional, BTreeSet::from([String::from("url")]));
        assert!(parse_metadata("[]").is_err());
    }

    #[test]
    fn the_committed_table_is_fresh() {
        let root = crate::repo_root();
        docs(&root, false).unwrap();
    }
}
